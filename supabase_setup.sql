-- Schéma de départ pour Supabase. À exécuter dans SQL Editor.
-- AVERTISSEMENT : ces règles autorisent les utilisateurs connectés. Il faut terminer
-- l'écran d'authentification et configurer les 6 comptes avant un usage privé réel.
create table if not exists public.events (
 id bigint generated by default as identity primary key,
 title text not null check (char_length(title) between 1 and 90),
 sport text not null check (sport in ('VTT','Course à pied','Vélo de route','Triathlon','Natation')),
 date date not null check (date >= '2026-01-01' and date <= '2026-12-31'),
 time time,
 distance numeric(6,1) check (distance is null or distance >= 0),
 location text,
 route text,
 organizer text not null check (organizer in ('Julien','Stéphanie','François','Bérénice','Jérôme','Annabelle')),
 responses jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
alter table public.events enable row level security;
drop policy if exists "group members can read events" on public.events;
create policy "group members can read events" on public.events for select to authenticated using (true);
drop policy if exists "group members can create events" on public.events;
create policy "group members can create events" on public.events for insert to authenticated with check (true);
drop policy if exists "group members can update events" on public.events;
create policy "group members can update events" on public.events for update to authenticated using (true) with check (true);
drop policy if exists "group members can delete events" on public.events;
create policy "group members can delete events" on public.events for delete to authenticated using (true);
alter publication supabase_realtime add table public.events;
